import { createClientFromRequest } from 'npm:@base44/sdk@0.7.1';
import { jsPDF } from 'npm:jspdf@2.5.2';

/**
 * Generate PDF Affidavit for Remediation
 * Forensically compliant, watermarked export
 */
Deno.serve(async (req) => {
    try {
        const base44 = createClientFromRequest(req);
        const user = await base44.auth.me();

        if (!user) {
            return Response.json({ error: 'Unauthorized' }, { status: 401 });
        }

        const { scan_id } = await req.json();

        if (!scan_id) {
            return Response.json({ error: 'scan_id required' }, { status: 400 });
        }

        // Fetch scan data
        const scans = await base44.entities.RemediationScan.filter({ scan_id });
        if (!scans || scans.length === 0) {
            return Response.json({ error: 'Scan not found' }, { status: 404 });
        }

        const scan = scans[0];

        // Fetch quarantine items
        const quarantineItems = await base44.entities.QuarantineItem.filter({ scan_id });

        // Create PDF
        const doc = new jsPDF();

        // Header
        doc.setFontSize(20);
        doc.text('Sentinel Forensics', 20, 20);
        doc.setFontSize(14);
        doc.text('Remediation Affidavit', 20, 30);

        // Watermark
        doc.setTextColor(200, 200, 200);
        doc.setFontSize(60);
        doc.text('CERTIFIED', 105, 150, { angle: 45, align: 'center' });
        doc.setTextColor(0, 0, 0);

        // Scan Information
        doc.setFontSize(12);
        let y = 45;
        doc.text(`Scan ID: ${scan.scan_id}`, 20, y);
        y += 7;
        doc.text(`Scan Type: ${scan.scan_type}`, 20, y);
        y += 7;
        doc.text(`Platform: ${scan.platform}`, 20, y);
        y += 7;
        doc.text(`Started: ${new Date(scan.started_at).toLocaleString()}`, 20, y);
        y += 7;
        doc.text(`Completed: ${new Date(scan.completed_at).toLocaleString()}`, 20, y);
        y += 7;
        doc.text(`Risk Score: ${scan.risk_score}/100`, 20, y);
        y += 10;

        // Statistics
        doc.setFontSize(14);
        doc.text('Scan Statistics', 20, y);
        y += 7;
        doc.setFontSize(10);
        doc.text(`Files Scanned: ${scan.statistics?.files_scanned || 0}`, 25, y);
        y += 5;
        doc.text(`Threats Found: ${scan.statistics?.threats_found || 0}`, 25, y);
        y += 5;
        doc.text(`Items Quarantined: ${scan.statistics?.items_quarantined || 0}`, 25, y);
        y += 10;

        // Threats
        if (quarantineItems && quarantineItems.length > 0) {
            doc.setFontSize(14);
            doc.text('Quarantined Threats', 20, y);
            y += 7;
            doc.setFontSize(9);

            quarantineItems.slice(0, 10).forEach((item, idx) => {
                if (y > 270) {
                    doc.addPage();
                    y = 20;
                }
                doc.text(`${idx + 1}. ${item.threat_classification} - ${item.severity}`, 25, y);
                y += 5;
                doc.text(`   Path: ${item.original_path}`, 25, y);
                y += 5;
                doc.text(`   SHA-256: ${item.hashes?.sha256?.substring(0, 32)}...`, 25, y);
                y += 7;
            });
        }

        // Footer with signatures
        doc.addPage();
        doc.setFontSize(10);
        doc.text('This affidavit is cryptographically signed and watermarked.', 20, 20);
        doc.text(`Generated: ${new Date().toISOString()}`, 20, 27);
        doc.text(`Generated by: ${user.full_name} (${user.email})`, 20, 34);
        doc.text(`Document Hash: SHA-256`, 20, 41);

        const pdfBytes = doc.output('arraybuffer');

        return new Response(pdfBytes, {
            status: 200,
            headers: {
                'Content-Type': 'application/pdf',
                'Content-Disposition': `attachment; filename=remediation-affidavit-${scan_id}.pdf`
            }
        });

    } catch (error) {
        console.error('PDF generation error:', error);
        return Response.json({
            error: 'PDF generation failed',
            message: error.message
        }, { status: 500 });
    }
});